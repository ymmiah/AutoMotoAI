/* Developer Studio V11 — explicitly approved local PDF compilation and SyncTeX. */
export function mountDeveloperTexBuild({api,host,getProject,editor,status}) {
  const BASE="/api/developer/studio/texbuild";
  const root=host.querySelector("#dsTexBuildRoot");
  root.innerHTML=
    '<section class="ds-texbuild-panel" aria-label="Local TeX build and PDF preview">'+
      '<div class="ds-texbuild-head"><h3>TeX build & PDF preview · V11</h3>'+
        '<span class="ds-texbuild-guard">EXPLICIT BUILD ONLY</span></div>'+
      '<div class="ds-texbuild-body">'+
        '<p class="ds-footnote">Build a bounded copy of a trusted local LaTeX project using an already installed Tectonic or latexmk tool. Compiler invocation is not an OS sandbox: TeX packages and programs may still access files or the network. No automatic compilation, package download or shell escape is requested.</p>'+
        '<div class="ds-texbuild-toolbar">'+
          '<label for="dsTexBuildMain">Main document</label>'+
          '<input id="dsTexBuildMain" class="input" maxlength="1024" spellcheck="false" placeholder="main.tex">'+
          '<label for="dsTexBuildEngine">Local compiler</label>'+
          '<select class="input" id="dsTexBuildEngine" disabled><option value="">Inspect installed compilers</option></select>'+
          '<button id="dsTexBuildInspect" class="btn sm" type="button">Inspect tools</button>'+
          '<button id="dsTexBuildRun" class="btn sm primary" type="button" disabled>Approve & build PDF</button>'+
        '</div>'+
        '<p class="ds-footnote" id="dsTexBuildStatus" role="status" aria-live="polite">Open a trusted local project to use the TeX build tools.</p>'+
        '<div class="ds-texbuild-summary" id="dsTexBuildSummary" role="region" aria-label="Build diagnostics"></div>'+
        '<div class="ds-texbuild-navigate">'+
          '<label for="dsTexBuildSource">Source-to-PDF</label>'+
          '<input class="input" id="dsTexBuildSource" placeholder="chapters/introduction.tex" maxlength="1024" spellcheck="false">'+
          '<label for="dsTexBuildLine">Line</label><input class="input" type="number" id="dsTexBuildLine" min="1" max="1000000" value="1">'+
          '<button class="btn sm" id="dsTexBuildForward" disabled type="button">Find PDF page</button>'+
          '<label for="dsTexBuildPage">PDF page</label><input class="input" type="number" id="dsTexBuildPage" min="1" max="10000" value="1">'+
          '<button class="btn sm" id="dsTexBuildReverse" disabled type="button">Find source on page</button>'+
        '</div>'+
        '<div class="ds-texbuild-preview-controls">'+
          '<button class="btn sm" id="dsTexBuildPreview" disabled type="button">Load PDF preview</button>'+
          '<button class="btn sm" id="dsTexBuildNewTab" disabled type="button">Open PDF separately</button>'+
          '<button class="btn sm" id="dsTexBuildDownload" disabled type="button">Save a copy</button>'+
        '</div>'+
        '<iframe id="dsTexBuildFrame" class="ds-texbuild-frame" title="Ephemeral compiled LaTeX PDF preview" loading="lazy" sandbox="allow-scripts" referrerpolicy="no-referrer" hidden></iframe>'+
        '<p class="ds-footnote">SyncTeX mapping is available only when generated by the compiler. Page jumps may be approximate: exact PDF coordinate tracking and reverse click-to-source are not claimed. PDF previews are temporary and not saved in the source project.</p>'+
      '</div></section>';
  const el=id=>root.querySelector("#"+id);
  let checked=[], build=null, busy=false, projectSeq=0, objectUrl=null, mainPath="";
  const project=()=>getProject()?.project||null;
  const active=()=>editor.lspContext();
  function message(value,bad=false) {
    const node=el("dsTexBuildStatus");
    node.textContent=value;node.classList.toggle("ds-error",bad);
  }
  function clearPreview(){
    if(objectUrl){URL.revokeObjectURL(objectUrl);objectUrl=null;}
    const frame=el("dsTexBuildFrame");frame.removeAttribute("src");frame.hidden=true;
    el("dsTexBuildSummary").replaceChildren();
  }
  function resetBuild(){
    build=null;clearPreview();
    controls();
  }
  function choice(){return checked.find(x=>x.name===el("dsTexBuildEngine").value &&
                                              x.status==="installed_not_executed");}
  function controls(){
    const can=!!project()&&!!getProject()?.trusted&&!busy;
    el("dsTexBuildRun").disabled=!can||!choice()||!el("dsTexBuildMain").value.trim();
    el("dsTexBuildInspect").disabled=busy||!project();
    const hasBuild=can&&!!build?.pdf_ready;
    el("dsTexBuildPreview").disabled=!hasBuild;
    el("dsTexBuildForward").disabled=!hasBuild||!build?.synctex_available;
    el("dsTexBuildReverse").disabled=!hasBuild||!build?.synctex_available;
    el("dsTexBuildNewTab").disabled=!hasBuild||!objectUrl;
    el("dsTexBuildDownload").disabled=!hasBuild||!objectUrl;
  }
  function appendInfo(value,kind="note"){
    const row=document.createElement("p");row.className="ds-texbuild-info";
    row.textContent=String(value);row.dataset.kind=kind;
    el("dsTexBuildSummary").append(row);
  }
  function buildSummary(item){
    el("dsTexBuildSummary").replaceChildren();
    appendInfo("Engine: "+item.compiler+" · "+item.status+
      " · "+item.elapsed_ms+" ms · input "+item.input_file_count+
      " file(s) · "+(item.input_bytes||0)+" B");
    if(item.pdf_ready){
      appendInfo("PDF: "+item.pdf_size+" bytes · SHA-256 "+item.pdf_sha256);
      appendInfo(item.synctex_available?
        item.synctex_records+" source-to-page pins available":
        "No usable SyncTeX mappings were generated; navigation is disabled.");
    }
    appendInfo("Figures: "+(item.figures||[]).length+" · tables: "+
      (item.table_locations||[]).length+" (static source counts).");
    for(const warning of (item.diagnostics||[]).slice(0,90)){
      const row=document.createElement("div");row.className="ds-texbuild-diagnostic";
      const text=document.createElement("span");
      text.textContent=warning.severity+" · "+(warning.path||"compiler")+
        (warning.line?":"+warning.line:"")+" · "+warning.message;
      row.append(text);
      if(warning.path&&warning.line){
        const jump=document.createElement("button");jump.className="btn sm";jump.type="button";
        jump.textContent="Go to source";
        jump.onclick=()=>void revealSource(warning.path,warning.line);
        row.append(jump);
      }
      el("dsTexBuildSummary").append(row);
    }
    if(item.build_log){
      const details=document.createElement("details");
      const heading=document.createElement("summary");heading.textContent="Bounded compiler log";
      const pre=document.createElement("pre");pre.textContent=item.build_log;
      details.append(heading,pre);el("dsTexBuildSummary").append(details);
    }
    appendInfo("External compilers are not sandboxed. Source inputs are snapshots; other host-file writes are not independently ruled out.","warning");
  }
  async function inspect(){
    const current=project();if(!current||busy)return;
    const seq=++projectSeq;busy=true;controls();
    message("Inspecting installed TeX compiler paths and hashes; nothing is executed.");
    try{
      const data=await api(BASE+"/engines?"+new URLSearchParams({project:current}));
      if(seq!==projectSeq||project()!==current||!root.isConnected)return;
      checked=data.engines||[];
      const select=el("dsTexBuildEngine"),was=select.value;
      select.replaceChildren();select.add(new Option("Choose a recognised local TeX tool",""));
      for(const item of checked){
        const label=item.name+" · "+(item.status==="installed_not_executed"?
          "installed, SHA-256 checked":"not available");
        select.add(new Option(label,item.name));
        if(item.status!=="installed_not_executed")select.options[select.options.length-1].disabled=true;
      }
      select.disabled=!checked.some(x=>x.status==="installed_not_executed");
      if(checked.some(x=>x.name===was&&x.status==="installed_not_executed"))select.value=was;
      message(select.disabled?
        "No approved installed Tectonic/latexmk compiler detected. V9 static analysis remains available.":
        "Compiler fingerprint inspected. Starting a build requires a separate consent prompt.");
    }catch(error){message("Compiler inspection failed: "+error.message,true);}
    finally{busy=false;controls();}
  }
  function payload(){
    const where=project(),main=el("dsTexBuildMain").value.trim();
    if(!where||!main)return null;
    const request={project:where,main};
    const context=active();
    if(context?.path?.toLowerCase().endsWith(".tex")){
      request.active_path=context.path;
      request.active_text=context.text;
    }
    return request;
  }
  async function compile(){
    const request=payload(),selected=choice();
    if(!request||!selected||!getProject()?.trusted||busy)return;
    const warning="Run the installed "+selected.name+" TeX compiler on a temporary "+
      "snapshot of this trusted project? This is REAL external process execution, "+
      "not an operating-system sandbox. It can access host files and may run "+
      "external dependencies despite restrictive flags. No packages will be "+
      "automatically downloaded by AutoMoto. Continue?";
    if(!window.confirm(warning))return;
    const seq=++projectSeq;busy=true;controls();resetBuild();
    message("Compiling an isolated source snapshot with fixed no-shell-escape flags…");
    try{
      const result=await api(BASE+"/build",{...request,engine:selected.name,
        expected_sha256:selected.sha256,expected_executable:selected.executable,
        confirmed:true,acknowledge_external_process_risk:true});
      if(seq!==projectSeq||project()!==request.project||!root.isConnected)return;
      build=result;
      buildSummary(result);
      message(result.pdf_ready?
        "PDF build succeeded. Preview is temporary; load it explicitly below.":
        "Compiler status: "+result.status+". Review the diagnostics and log.",!result.pdf_ready);
    }catch(error){message("TeX build rejected or failed: "+error.message,true);}
    finally{busy=false;controls();}
  }
  async function preview(){
    const where=project(),item=build;
    if(!where||!item?.pdf_ready||busy)return;
    const seq=++projectSeq;busy=true;controls();
    try{
      const response=await api(BASE+"/preview",{project:where,build_id:item.build_id});
      if(seq!==projectSeq||project()!==where)return;
      // Use a local blob: no remote preview service or unapproved upload.
      const binary=atob(response.pdf_base64), bytes=new Uint8Array(binary.length);
      for(let i=0;i<binary.length;i++)bytes[i]=binary.charCodeAt(i);
      if(bytes.length>4194304||bytes.length<8)throw Error("Invalid preview size");
      if(objectUrl)URL.revokeObjectURL(objectUrl);
      objectUrl=URL.createObjectURL(new Blob([bytes],{type:"application/pdf"}));
      const frame=el("dsTexBuildFrame");
      frame.src=objectUrl+"#page=1";frame.hidden=false;
      message("Ephemeral local PDF loaded. Preview expires server-side and is not written into your project.");
    }catch(error){message("PDF preview unavailable: "+error.message,true);}
    finally{busy=false;controls();}
  }
  async function revealSource(path,line){
    try{
      if(!getProject())return;
      await editor.openFile(path);
      editor.revealLocation(path,line,1);
    }catch(error){message("Unable to open original source: "+error.message,true);}
  }
  async function forward(){
    const where=project(),item=build;if(!where||!item?.synctex_available||busy)return;
    const path=el("dsTexBuildSource").value.trim();
    const line=Number(el("dsTexBuildLine").value);
    if(!path||!Number.isInteger(line)||line<1)return;
    try{
      const mapping=await api(BASE+"/sync/source-to-pdf",
        {project:where,build_id:item.build_id,path,line});
      if(project()!==where)return;
      el("dsTexBuildPage").value=String(mapping.page);
      if(objectUrl){
        const frame=el("dsTexBuildFrame");frame.src=objectUrl+"#page="+mapping.page;
      }
      message("Source line "+line+" maps to PDF page "+mapping.page+
        " (nearest SyncTeX line "+mapping.matched_line+
        (mapping.exact_line_match?"":", approximate")+").");
    }catch(error){message("Source-to-PDF mapping unavailable: "+error.message,true);}
  }
  async function reverse(){
    const where=project(),item=build;if(!where||!item?.synctex_available||busy)return;
    const page=Number(el("dsTexBuildPage").value);
    if(!Number.isInteger(page)||page<1)return;
    try{
      const mapping=await api(BASE+"/sync/page-to-source",
        {project:where,build_id:item.build_id,page});
      if(project()!==where)return;
      await revealSource(mapping.path,mapping.line);
      message("Approximate page "+page+" → "+mapping.path+":"+mapping.line+
        ". Exact click-coordinate reverse navigation is not implemented.");
    }catch(error){message("Page-to-source mapping unavailable: "+error.message,true);}
  }
  function fileChanged(path){
    if(path?.toLowerCase().endsWith(".tex")){
      el("dsTexBuildSource").value=path;
      if(!el("dsTexBuildMain").value)el("dsTexBuildMain").value=path;
    }
    controls();
  }
  function projectChanged(){
    projectSeq++;busy=false;checked=[];build=null;clearPreview();
    el("dsTexBuildMain").value="";
    el("dsTexBuildSource").value="";
    el("dsTexBuildEngine").replaceChildren(new Option("Inspect installed compilers",""));
    el("dsTexBuildEngine").disabled=true;
    message("Open a trusted local project to inspect its installed compiler.");controls();
  }
  function trustChanged(){
    if(!getProject()?.trusted)resetBuild();
    controls();
  }
  el("dsTexBuildMain").addEventListener("input",()=>{resetBuild();controls();});
  el("dsTexBuildEngine").addEventListener("change",()=>{resetBuild();controls();});
  el("dsTexBuildInspect").onclick=()=>void inspect();
  el("dsTexBuildRun").onclick=()=>void compile();
  el("dsTexBuildPreview").onclick=()=>void preview();
  el("dsTexBuildForward").onclick=()=>void forward();
  el("dsTexBuildReverse").onclick=()=>void reverse();
  el("dsTexBuildNewTab").onclick=()=>{if(objectUrl)window.open(objectUrl,"_blank","noopener,noreferrer");};
  el("dsTexBuildDownload").onclick=()=>{
    if(!objectUrl)return;
    const link=document.createElement("a");link.href=objectUrl;
    link.download="automoto-tex-preview.pdf";link.click();
  };
  controls();
  return {projectChanged,trustChanged,fileChanged,inspect};
}
