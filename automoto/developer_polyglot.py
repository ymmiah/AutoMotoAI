def _bindings(rel: str, lang: str, text: str) -> list[dict]:
    out = []
    name = rel.rsplit("/", 1)[-1].casefold()

    def B(kind: str, label: str, pos: int = 0) -> None:
        out.append({"kind": kind, "label": label, "file": rel, "line": _line(text, pos)})
    if name == "binding.gyp":
        B("c-js", "C/C++ ↔ JavaScript (node-gyp)")
    if name == "pyproject.toml" and re.search(r"build-backend\s*=\s*['\"]maturin", text):
        B("rust-python", "Rust ↔ Python (maturin)")
    if name == "cargo.toml":
        for dep, label, kind in (("pyo3", "Rust ↔ Python (PyO3)", "rust-python"), ("napi", "Rust ↔ JavaScript (napi-rs)", "rust-js"),
                                 ("wasm-bindgen", "Rust ↔ JavaScript (wasm-bindgen)", "rust-js"),
                                 ("neon", "Rust ↔ JavaScript (Neon)", "rust-js")):
            m = re.search(rf"^\s*{re.escape(dep)}\s*=", text, re.M)
            if m:
                B(kind, label, m.start())
    for kind, label, rx, langs in BINDINGS:
        if lang in langs:
            m = rx.search(text)
            if m:
                B(kind, label, m.start())
    return out


