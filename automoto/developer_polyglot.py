def _norm(path: str) -> tuple[str, bool]:
    """Route or call address -> '/a/{}/b'. Also says whether it starts with a variable base URL."""
    p = path.strip()
    var_start = p.startswith("${") or p.startswith("{")
    p = re.sub(r"^https?://[^/]+", "", p)
    if var_start:
        p = re.sub(r"^(?:\$\{[^}]{0,80}\}|\{[^}]{0,80}\})", "", p)
    p = p.split("?")[0].split("#")[0]
    p = re.sub(r"\$\{[^}]{0,80}\}", "{}", p)
    p = re.sub(r"<(?:\w+:)?\w+>", "{}", p)
    p = re.sub(r"\{[^}/]{0,80}\}", "{}", p)
    p = re.sub(r"(?<=/):\w+\??", "{}", p)
    p = re.sub(r"\[\[?(?:\.\.\.)?\w+\]\]?", "{}", p)
    p = re.sub(r"\(\?P<\w+>[^)]{0,60}\)", "{}", p)
    p = p.replace("^", "").replace("$", "")
    if not p.startswith("/"):
        p = "/" + p
    p = re.sub(r"/{2,}", "/", p)
    if len(p) > 1:
        p = p.rstrip("/")
    return p, var_start


def _join(prefix: str, path: str) -> str:
    return "/" + "/".join(x for x in (prefix.strip("/"), path.strip("/")) if x)


def _routes(rel: str, lang: str, text: str) -> list[dict]:
    out: list[dict] = []

    def R(method: str, path: str, pos: int, handler: str | None, framework: str) -> None:
        out.append({"method": method.upper(), "path": _norm(path)[0], "raw": _clip(path, 200), "file": rel,
                    "line": _line(text, pos), "handler": handler, "framework": framework})
    if lang == "python":
        prefixes = {}
        for m in PY_PREFIX.finditer(text):
            pm = re.search(r"(?:prefix|url_prefix)\s*=\s*['\"]([^'\"]{0,200})['\"]", m.group(2))
            prefixes[m.group(1)] = pm.group(1) if pm else ""
        for m in PY_ROUTE.finditer(text):
            obj, verb, path, rest = m.group(1), m.group(2), m.group(4), m.group(5)
            d = PY_DEF.search(text, m.end())
            methods = [verb]
            if verb in ("route", "api_route"):
                mm = re.search(r"methods\s*=\s*[\[(]([^\])]{0,100})[\])]", rest)
                methods = re.findall(r"['\"](\w+)['\"]", mm.group(1)) if mm else ["GET"]
            for mth in methods:
                R(mth, _join(prefixes.get(obj, ""), path), m.start(), d.group(1) if d else None,
                  "Flask" if verb == "route" else "FastAPI")
        if rel.endswith("urls.py"):
            for m in DJ_PATH.finditer(text):
                R("ANY", "/" + m.group(2), m.start(), m.group(3).split(".")[-1], "Django")
    elif lang in ("javascript", "typescript"):
        servers = {m.group(1) for m in JS_SERVER.finditer(text)}
        if servers or re.search(r"""from\s+['"](?:express|koa|hono|fastify|elysia|@koa/router)['"]|require\(\s*['"](?:express|koa|fastify)['"]""", text):
            servers |= {"app", "router", "server", "routes"}
            for m in JS_ROUTE.finditer(text):
                if m.group(1) in servers:
                    h = re.match(r"\s*(?:[\w$.]+\s*,\s*)*([A-Za-z_$][\w$.]*)\s*\)", text[m.end(): m.end() + 200])
                    R("ANY" if m.group(2) == "all" else m.group(2), m.group(4), m.start(), h.group(1) if h else None, "Express-style")
        nm = re.match(r"^(?:.*/)?(?:src/)?(app|pages)/(.*)$", rel)
        if nm:
            sub = nm.group(2)
            if nm.group(1) == "app" and re.search(r"(^|/)route\.(?:ts|js|mjs)$", sub):
                parts = [s for s in sub.split("/")[:-1] if not (s.startswith("(") and s.endswith(")"))]
                for m in NEXT_EXPORT.finditer(text):
                    R(m.group(1), "/" + "/".join(parts), m.start(), m.group(1), "Next.js route")
            elif nm.group(1) == "pages" and sub.startswith("api/"):
                p = re.sub(r"(/index)?\.(?:ts|js|tsx|jsx)$", "", sub)
                R("ANY", "/" + p, 0, "handler", "Next.js API")
    elif lang in ("java", "kotlin"):
        cm = SPRING_CLASS.search(text)
        prefix = cm.group(1) if cm else ""
        for m in SPRING_ROUTE.finditer(text):
            if cm and cm.start() <= m.start() < cm.end():
                continue
            d = re.search(r"(?:public|fun)\s+(?:[\w<>,?\s]+\s+)?(\w+)\s*\(", text[m.end(): m.end() + 400])
            R("ANY" if m.group(1) == "Request" else m.group(1), _join(prefix, m.group(2) or ""), m.start(),
              d.group(1) if d else None, "Spring")
    elif lang == "go":
        for m in GO_ROUTE.finditer(text):
            verb, p = m.group(1).upper(), m.group(2)
            mv = re.match(r"(GET|POST|PUT|PATCH|DELETE)\s+(/.*)", p)
            if mv:
                verb, p = mv.group(1), mv.group(2)
            R("ANY" if verb in ("HANDLEFUNC", "HANDLE") else verb, p, m.start(),
              (m.group(3) or "").split(".")[-1] or None, "Go")
    elif lang == "csharp":
        cm = CS_CLASS_ROUTE.search(text)
        prefix = cm.group(1).replace("[controller]", re.sub(r"Controller$", "", cm.group(2)).lower()) if cm else ""
        for m in CS_ROUTE.finditer(text):
            d = re.search(r"public\s+[\w<>\[\],\s]+?\s(\w+)\s*\(", text[m.end(): m.end() + 300])
            R(m.group(1), _join(prefix, m.group(2) or ""), m.start(), d.group(1) if d else None, "ASP.NET")
        for m in CS_MIN.finditer(text):
            R(m.group(1), m.group(2), m.start(), None, "ASP.NET minimal API")
    elif lang == "php" and re.search(r"(^|/)routes/[\w.-]+\.php$", rel):
        prefix = "/api" if rel.endswith("api.php") else ""
        for m in LARAVEL.finditer(text):
            R("ANY" if m.group(1) == "any" else m.group(1), _join(prefix, m.group(3)), m.start(), None, "Laravel")
    elif lang == "ruby" and rel.endswith("config/routes.rb"):
        for m in RAILS_VERB.finditer(text):
            R(m.group(1), m.group(2), m.start(), None, "Rails")
        for m in RAILS_RES.finditer(text):
            n = m.group(1)
            for verb, p in (("GET", f"/{n}"), ("POST", f"/{n}"), ("GET", f"/{n}/{{id}}"), ("PATCH", f"/{n}/{{id}}"),
                            ("PUT", f"/{n}/{{id}}"), ("DELETE", f"/{n}/{{id}}")):
                R(verb, p, m.start(), f"{n}#resources", "Rails resources")
    return out[:500]


def _args(text: str, pos: int, limit: int = 600) -> str:
    """The rest of a call's own arguments (up to its closing bracket), so options of a later call aren't read."""
    depth = 1
    end = min(len(text), pos + limit)
    for i in range(pos, end):
        if text[i] in "([{":
            depth += 1
        elif text[i] in ")]}":
            depth -= 1
            if depth == 0:
                return text[pos:i]
    return text[pos:end]


def _calls(rel: str, lang: str, text: str) -> list[dict]:
    if lang not in ("javascript", "typescript", "vue", "svelte", "html"):
        return []
    out: list[dict] = []
    for rx, kind in ((FETCH, "fetch"), (AXIOS, "client"), (SWR, "hook")):
        for m in rx.finditer(text):
            if kind == "client":
                verb, raw = m.group(1).upper(), m.group(3)
            else:
                raw = m.group(2)
                near = METHOD_NEAR.search(_args(text, m.end())) if kind == "fetch" else None
                verb = near.group(1).upper() if near else "GET"
            if not (raw.startswith(("/", "http://", "https://", "${", "{", "api/"))):
                continue
            if re.match(r"https?://", raw) and not re.match(r"https?://(?:localhost|127\.0\.0\.1|0\.0\.0\.0)(?::\d+)?/", raw):
                continue  # an outside website, not this project's backend
            p, var = _norm(raw)
            out.append({"method": verb, "path": p, "raw": _clip(raw, 200), "file": rel, "line": _line(text, m.start()),
                        "variable_base": var, "via": kind})
    return out[:500]


