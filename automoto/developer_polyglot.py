def _imports(lang: str, text: str) -> list[tuple[str, int, str]]:
    """(spec, line, kind); kind tells the resolver how to look the spec up."""
    out: list[tuple[str, int, str]] = []

    def add(spec: str, pos: int, kind: str) -> None:
        out.append((spec.strip(), _line(text, pos), kind))
    if lang in ("python", "cython"):
        for m in PY_IMPORT.finditer(text):
            if m.group(1) is not None:
                names = [n.strip(" ()\t").split(" as ")[0].strip() for n in m.group(2).split(",")]
                add(m.group(1), m.start(), "py-from:" + ",".join(n for n in names[:20] if n))
            else:
                for n in m.group(3).split(","):
                    n = n.split(" as ")[0].strip()
                    if n:
                        add(n, m.start(), "py")
    elif lang in ("javascript", "typescript", "vue", "svelte"):
        for m in JS_IMPORT.finditer(text):
            add(m.group(2), m.start(), "js")
    elif lang == "go":
        for b in GO_IMPORT_BLOCK.finditer(text):
            for m in re.finditer(r'"([^"]+)"', b.group(1)):
                add(m.group(1), b.start(1) + m.start(), "go")
        for m in GO_IMPORT_ONE.finditer(text):
            add(m.group(1), m.start(), "go")
    elif lang == "rust":
        for m in RS_MOD.finditer(text):
            add(m.group(1), m.start(), "rs-mod")
        for m in RS_USE.finditer(text):
            add(m.group(1) + m.group(2), m.start(), "rs-use")
        for m in RS_EXT.finditer(text):
            if m.group(1) not in ("crate", "super", "self", "std", "core", "alloc"):
                add(m.group(1), m.start(), "ext")
    elif lang in ("java", "kotlin", "scala"):
        for m in JV_IMPORT.finditer(text):
            add(m.group(1), m.start(), "jvm")
    elif lang in ("c", "cpp", "objc"):
        for m in C_INCLUDE.finditer(text):
            add(m.group(2), m.start(), "c-local" if m.group(1) == '"' else "ext")
    elif lang == "php":
        for m in PHP_REQ.finditer(text):
            add(m.group(2), m.start(), "rel")
        for m in PHP_USE.finditer(text):
            add(m.group(1), m.start(), "php-use")
    elif lang == "ruby":
        for m in RB_REQ.finditer(text):
            add(m.group(3), m.start(), "rel-rb" if m.group(1) else "rb")
    elif lang == "css":
        for m in CSS_IMPORT.finditer(text):
            add(m.group(2), m.start(), "rel")
    elif lang == "html":
        for m in HTML_REF.finditer(text):
            add(m.group(2), m.start(), "rel")
    elif lang == "csharp":
        for m in CS_USING.finditer(text):
            add(m.group(1), m.start(), "ext")
    elif lang in ("swift", "dart"):
        for m in SWIFT_DART_IMPORT.finditer(text):
            spec = m.group(1) or m.group(2)
            add(spec, m.start(), "dart" if lang == "dart" else "ext")
    return out[:400]


def _models(rel: str, lang: str, text: str) -> tuple[list[dict], list[dict]]:
    models: list[dict] = []
    rels: list[dict] = []

    def M(name: str, pos: int, kind: str, table: str | None = None) -> None:
        models.append({"name": name, "file": rel, "line": _line(text, pos), "kind": kind, **({"table": table} if table else {})})

    def R(a: str, b: str, pos: int, how: str) -> None:
        rels.append({"from": a, "to": b, "file": rel, "line": _line(text, pos), "how": how})
    if lang == "sql":
        for m in SQL_TABLE.finditer(text):
            M(m.group(1), m.start(), "SQL table", m.group(1))
            for r in SQL_REF.finditer(m.group(2)):
                R(m.group(1), r.group(1), m.start(2) + r.start(), "foreign key")
    elif lang == "prisma":
        found = list(PRISMA_MODEL.finditer(text))
        names = {m.group(1) for m in found}
        for m in found:
            M(m.group(1), m.start(), "Prisma model")
            for fl in re.finditer(r"^\s*\w+\s+(\w+)(\[\])?\??", m.group(2), re.M):
                if fl.group(1) in names and fl.group(1) != m.group(1):
                    R(m.group(1), fl.group(1), m.start(2) + fl.start(), "has many" if fl.group(2) else "relation")
    elif lang == "python":
        classes = list(PY_CLASS.finditer(text))
        for i, m in enumerate(classes):
            body = text[m.end(): classes[i + 1].start() if i + 1 < len(classes) else len(text)]
            bases = m.group(2)
            tm = SA_TABLE.search(body)
            if "models.Model" in bases:
                M(m.group(1), m.start(), "Django model")
                for r in DJ_REL.finditer(body):
                    R(m.group(1), r.group(2).split(".")[-1], m.end() + r.start(), r.group(1))
            elif tm or "db.Model" in bases or re.search(r"\b(?:DeclarativeBase|SQLModel)\b", bases) or (
                    re.search(r"\bBase\b", bases) and "sqlalchemy" in text):
                M(m.group(1), m.start(), "SQLAlchemy model", tm.group(1) if tm else None)
                for r in SA_REL.finditer(body):
                    R(m.group(1), r.group(1) or r.group(2), m.end() + r.start(),
                      "relationship" if r.group(1) else "foreign key")
    elif lang in ("typescript", "javascript"):
        ents = list(TS_ENTITY.finditer(text))
        for i, m in enumerate(ents):
            M(m.group(1), m.start(), "TypeORM entity")
            body = text[m.end(): ents[i + 1].start() if i + 1 < len(ents) else len(text)]
            for r in TS_REL.finditer(body):
                R(m.group(1), r.group(2), m.end() + r.start(), r.group(1))
    elif lang == "ruby":
        for m in RB_MODEL.finditer(text):
            M(m.group(1), m.start(), "ActiveRecord model")
            for r in RB_REL.finditer(text, m.end()):
                t = r.group(2)
                if r.group(1) in ("has_many", "has_and_belongs_to_many") and t.endswith("s"):
                    t = t[:-1]
                R(m.group(1), "".join(p[:1].upper() + p[1:] for p in t.split("_")), r.start(), r.group(1))
    elif lang == "php":
        for m in PHP_MODEL.finditer(text):
            M(m.group(1), m.start(), "Eloquent model")
            for r in PHP_REL.finditer(text, m.end()):
                R(m.group(1), r.group(2), r.start(), r.group(1))
    elif lang in ("java", "kotlin"):
        for m in JPA_ENTITY.finditer(text):
            M(m.group(1), m.start(), "JPA entity")
            for r in JPA_REL.finditer(text, m.end()):
                R(m.group(1), r.group(2), r.start(), r.group(1))
    return models[:200], rels[:400]


