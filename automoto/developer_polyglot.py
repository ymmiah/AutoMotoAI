def _lang(rel: str) -> Optional[str]:
    name = rel.rsplit("/", 1)[-1].casefold()
    if name in ("cmakelists.txt", "makefile", "gemfile"):
        return "build"
    return EXT.get(PurePosixPath(name).suffix)


def _is_manifest(rel: str) -> bool:
    name = rel.rsplit("/", 1)[-1].casefold()
    return name in MANIFESTS or name.endswith((".sln", ".csproj", ".fsproj"))


def _walk(root: Path, deadline: float):
    todo = [(root, 0)]
    dirs = files = 0
    notes: list[str] = []
    while todo and dirs < MAX_DIRS and files < MAX_FILES:
        if time.monotonic() > deadline:
            notes.append("time")
            break
        directory, depth = todo.pop(0)
        dirs += 1
        try:
            with os.scandir(directory) as listing:
                items = []
                for entry in listing:
                    if len(items) >= MAX_DIR_ITEMS:
                        notes.append("wide folder")
                        break
                    items.append(entry)
        except OSError:
            continue
        items.sort(key=lambda e: e.name.casefold())
        for entry in items:
            try:
                if entry.is_symlink():
                    continue
                is_dir = entry.is_dir(follow_symlinks=False)
                if dindex._excluded(entry.name, is_dir) or (is_dir and entry.name.startswith(".")):
                    continue
                child = Path(entry.path)
                if getattr(child, "is_junction", lambda: False)():
                    continue
                rel = child.relative_to(root).as_posix()
                if is_dir:
                    if depth < MAX_DEPTH:
                        todo.append((child, depth + 1))
                    else:
                        notes.append("deep folder")
                elif entry.is_file(follow_symlinks=False):
                    if files >= MAX_FILES:
                        notes.append("file limit")
                        break
                    files += 1
                    yield rel, None
            except (OSError, ValueError):
                continue
    if todo or dirs >= MAX_DIRS or files >= MAX_FILES:
        notes.append("limit")
    if notes:
        yield None, sorted(set(notes))


def _read(root: Path, rel: str) -> Optional[tuple[str, str, int]]:
    """Bounded UTF-8 text through a no-follow descriptor, or None (binary, too big, linked, private)."""
    try:
        path = studio._path(root, rel)
    except HTTPException:
        return None
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_BINARY", 0)
    try:
        with os.fdopen(os.open(path, flags), "rb") as f:
            info = os.fstat(f.fileno())
            if not stat.S_ISREG(info.st_mode) or info.st_size > MAX_FILE_BYTES:
                return None
            raw = f.read(MAX_FILE_BYTES + 1)
        if len(raw) > MAX_FILE_BYTES or b"\x00" in raw[:8192]:
            return None
        return raw.decode("utf-8-sig"), hashlib.sha256(raw).hexdigest(), len(raw)
    except (OSError, UnicodeError):
        return None


def _line(text: str, pos: int) -> int:
    return text.count("\n", 0, pos) + 1


def _clip(s: str, n: int = 200) -> str:
    s = re.sub(r"[\x00-\x08\x0b-\x1f\x7f\u202a-\u202e\u2066-\u2069]", "", s or "")
    return s[:n]


