def _tomlish(text: Optional[str]) -> dict:
    if _toml is not None:
        try:
            return _toml.loads(text or "")
        except (ValueError, TypeError):
            return {}
    out: dict = {}
    section = out
    for line in (text or "").splitlines():
        line = line.split("#")[0].strip()
        m = re.match(r"\[([\w.\-]+)\]$", line)
