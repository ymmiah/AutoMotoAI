def rename_preview(root: Path, old: str, new: str, path: Optional[str] = None) -> dict:
    blocks: list[str] = []
    warnings: list[dict] = []
    for label, name in (("current", old), ("new", new)):
        if not IDENT.fullmatch(name or ""):
            raise HTTPException(422, f"The {label} name must be a plain code name (letters, digits, _ or $).")
    if old == new:
        raise HTTPException(422, "The new name is the same as the current name.")
    if new in RESERVED or old in RESERVED:
        raise HTTPException(422, "That's a reserved word in at least one language, so it can't be renamed safely.")
    scan = _scan(root)
    files = scan["files"]
    texts: dict[str, tuple[str, str]] = {}
    hits: dict[str, list[int]] = {}
    defs: dict[str, list[int]] = {}
    for rel in _code_files(scan):
        got = _read(root, rel)
        if not got or old not in got[0]:
            continue
        texts[rel] = (got[0], got[1])
        h = _code_hits(files[rel]["lang"], got[0], old)
        if h:
            hits[rel] = h
            d = _defines(files[rel]["lang"], got[0], old, h)
            if d:
                defs[rel] = d
    choices = [{"file": k, "lines": v[:5]} for k, v in sorted(defs.items())]
    core: Optional[str] = None
    if path:
        path = PurePosixPath(path.replace("\\", "/")).as_posix().lstrip("/")
        studio._path(root, path)
        if path not in defs:
            blocks.append(f"I can't find where {old} is defined in {path}.")
        else:
            core = path
    elif not defs:
        blocks.append(f"I can't find where {old} is defined, so I won't guess which uses belong together.")
    elif len(defs) > 1:
        blocks.append(f"{old} is defined in {len(defs)} files. Pick the file you mean so only its uses change.")
    else:
        core = next(iter(defs))
    scope: list[str] = []
    if core:
        importers = sorted({e["from"] for e in scan["edges"] if e["to"] == core})
        scope = [core] + [r for r in importers if r in hits]
        for r in scope[1:]:
            if r in defs:
                blocks.append(f"{r} also defines its own {old}, so the rename would be ambiguous there.")
        outside = sorted(set(hits) - set(scope))
        if outside:
            warnings.append({"kind": "outside", "text": f"{len(outside)} other file(s) use the name {old} but don't import "
                             f"{core}. They are not changed.", "files": outside[:10]})
    for r in list(scope):
        if files[r]["generated"]:
            scope.remove(r)
            warnings.append({"kind": "generated", "text": f"{r} looks generated ({files[r]['generated']}), so it's skipped. "
                             "Regenerate it after renaming.", "files": [r]})
    total = sum(len(hits[r]) for r in scope)
    if len(scope) > MAX_RENAME_FILES or total > MAX_RENAME_HITS:
        blocks.append(f"This would change {total} places in {len(scope)} files, which is more than is safe to do at once.")
    out_files = []
    for r in scope:
        text = texts[r][0]
        if _code_hits(files[r]["lang"], text, new):
            blocks.append(f"{new} is already used in {r}, so the rename would clash.")
        fresh = _apply(text, hits[r], old, new)
        if files[r]["lang"] == "python":
            try:
                ast.parse(text)
                try:
                    ast.parse(fresh)
                except SyntaxError as exc:
                    blocks.append(f"{r} wouldn't be valid Python after the change (line {exc.lineno}).")
            except SyntaxError:
                warnings.append({"kind": "syntax", "text": f"{r} already has a Python syntax problem.", "files": [r]})
        lines = sorted({_line(text, h) for h in hits[r]})
        src = text.split("\n")
        new_src = fresh.split("\n")
        out_files.append({"path": r, "count": len(hits[r]), "lines": lines[:50], "sha256": texts[r][1],
                          "language": NAMES.get(files[r]["lang"], files[r]["lang"]),
                          "examples": [{"line": ln, "before": _clip(src[ln - 1].strip(), 160),
                                        "after": _clip(new_src[ln - 1].strip(), 160)} for ln in lines[:3]]})
    contract = []
    for r in scope:
        for rt in files[r]["routes"]:
            if rt["handler"] == old:
                contract.append(f"{old} handles the API route {rt['method']} {rt['raw']} ({r}:{rt['line']}). The route address stays "
                                "the same, but check anything that refers to the handler by name.")
        for m in files[r]["models"]:
            if m["name"] == old:
                contract.append(f"{old} is a data model ({m['kind']}). Database tables, migrations and saved data "
                                "may still use the old name.")
    if contract:
        warnings.append({"kind": "contract", "text": " ".join(contract[:5]), "files": scope[:10]})
    if scan["budget"]["truncated"]:
        warnings.append({"kind": "partial", "text": "Your project is bigger than one map can hold, so some files weren't "
                         "checked.", "files": []})
    ready = not blocks and bool(scope)
    result = {"schema": SCHEMA, "state": "ready" if ready else "blocked", "old": old, "new": new, "defined_in": core,
              "choices": choices if len(defs) > 1 or (path and not core) else [], "blocks": blocks, "warnings": warnings,
              "files": out_files, "places": total, "needs_contract_ok": bool(contract), "action_sha256": None,
              "expires_in": PREVIEW_TTL, "source_modified": False, "source_executed": False}
    if ready:
        key = _key(root)
        payload = json.dumps({"project": key[0], "old": old, "new": new, "scope": scope,
                              "files": [[f["path"], f["sha256"], f["count"]] for f in out_files]}, sort_keys=True)
        action = hashlib.sha256(payload.encode("utf-8")).hexdigest()
        with LOCK:
            now = time.monotonic()
            for k in [k for k, v in _PREVIEWS.items() if now - v["created"] > PREVIEW_TTL]:
                _PREVIEWS.pop(k, None)
            _PREVIEWS[action] = {"key": key, "old": old, "new": new, "contract": bool(contract), "created": now,
                                 "files": {f["path"]: (f["sha256"], f["count"]) for f in out_files}}
        result["action_sha256"] = action
    return result


def rename_apply(root: Path, action: str, confirmed: bool, contract_ok: bool) -> dict:
    if not confirmed:
        raise HTTPException(422, "Confirm the rename first.")
    with LOCK, studio.STATE_LOCK:
        if not studio._trusted(root, studio._load()):
            raise HTTPException(403, "Trust this project first. Renaming changes files.")
        plan = _PREVIEWS.get(action)
        if not plan or time.monotonic() - plan["created"] > PREVIEW_TTL or plan["key"] != _key(root):
            _PREVIEWS.pop(action, None)
            raise HTTPException(409, "This preview has expired. Preview the rename again.")
        if plan["contract"] and not contract_ok:
            raise HTTPException(409, "This rename touches an API route or data model. Tick the box to say you've checked it.")
        _PREVIEWS.pop(action, None)
        staged = []
        for rel, (sha, count) in sorted(plan["files"].items()):
            file, data, info = _raw(root, rel)
            if hashlib.sha256(data).hexdigest() != sha:
                raise HTTPException(409, f"{rel} changed since the preview. Nothing was renamed. Preview again.")
            if not (stat.S_IMODE(info.st_mode) & stat.S_IWUSR):
                raise HTTPException(403, f"{rel} is read-only. Nothing was renamed.")
            text, bom = _text(data)
            lang = _lang(rel) or "other"
            hits = _code_hits(lang, text, plan["old"])
            if len(hits) != count:
                raise HTTPException(409, f"{rel} changed since the preview. Nothing was renamed.")
            fresh = (BOM if bom else b"") + _apply(text, hits, plan["old"], plan["new"]).encode("utf-8")
            staged.append((rel, file, data, fresh, stat.S_IMODE(info.st_mode)))
        done = []
        try:
            for rel, file, data, fresh, mode in staged:
                _atomic(file, fresh, mode)
                done.append((rel, file, data, mode))
        except OSError:
            for rel, file, data, mode in reversed(done):
                try:
                    _atomic(file, data, mode)
                except OSError:
                    pass
            raise HTTPException(500, "A file couldn't be written, so every change was put back.") from None
        undo_id = hashlib.sha256(f"{action}:{time.time_ns()}".encode()).hexdigest()[:32]
        _UNDO[undo_id] = {"key": plan["key"], "files": [(rel, data, hashlib.sha256(fresh).hexdigest(), mode)
                                                       for rel, _f, data, fresh, mode in staged]}
        while len(_UNDO) > 10:
            _UNDO.pop(next(iter(_UNDO)))
    with LOCK:
        CACHE.pop(plan["key"], None)
    return {"renamed": True, "old": plan["old"], "new": plan["new"], "files": [s[0] for s in staged],
            "places": sum(c for _s, c in plan["files"].values()), "undo_id": undo_id, "source_executed": False}


def rename_undo(root: Path, undo_id: str) -> dict:
    with LOCK, studio.STATE_LOCK:
        if not studio._trusted(root, studio._load()):
            raise HTTPException(403, "Trust this project first.")
        rec = _UNDO.get(undo_id)
        if not rec or rec["key"] != _key(root):
            raise HTTPException(404, "There's nothing to undo.")
        checks = []
        for rel, data, sha, mode in rec["files"]:
            file, now, _info = _raw(root, rel)
            if hashlib.sha256(now).hexdigest() != sha:
                raise HTTPException(409, f"{rel} has changed since the rename, so undo is off. Nothing was changed.")
            checks.append((file, data, mode))
        for file, data, mode in checks:
            _atomic(file, data, mode)
        _UNDO.pop(undo_id, None)
        CACHE.pop(rec["key"], None)
    return {"undone": True, "files": [r[0] for r in rec["files"]]}


