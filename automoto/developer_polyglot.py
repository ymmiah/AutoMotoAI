def _code_hits(lang: str, text: str, name: str) -> list[int]:
    """Offsets of `name` used as code: comments and plain strings are skipped."""
    if lang in ("python", "cython"):
        try:
            toks = list(tokenize.generate_tokens(io.StringIO(text).readline))
        except (tokenize.TokenError, IndentationError, SyntaxError):
            toks = None
        if toks is not None:
            starts = [0]
            for ln in text.splitlines(keepends=True):
                starts.append(starts[-1] + len(ln))
            return [starts[t.start[0] - 1] + t.start[1] for t in toks
                    if t.type == tokenize.NAME and t.string == name]
    out: list[int] = []
    i, n = 0, len(text)
    depth: list[int] = []  # JS template literal `${` nesting
    hash_c = lang in HASH_COMMENT or lang == "php"
    slash_c = lang not in NO_SLASH_COMMENT
    word = re.compile(r"[A-Za-z0-9_$]")
    while i < n:
        ch = text[i]
        if slash_c and text.startswith("//", i) or hash_c and ch == "#" and not (lang == "rust"):
            j = text.find("\n", i)
            i = n if j < 0 else j
            continue
        if slash_c and text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j < 0 else j + 2
            continue
        if ch in "\"'`":
            if ch == "'" and lang == "rust" and not re.match(r"'(?:\\.|[^\\'\n])'", text[i:i + 12]):
                i += 1  # a Rust lifetime such as 'a
                continue
            j = i + 1
            while j < n and text[j] != ch:
                if text[j] == "\\":
                    j += 2
                    continue
                if ch == "`" and lang in ("javascript", "typescript", "vue", "svelte") and text.startswith("${", j):
                    break
                if ch != "`" and text[j] == "\n":
                    break
                j += 1
            if j < n and ch == "`" and text.startswith("${", j):
                depth.append(1)
                i = j + 2
                continue
            i = j + 1
            continue
        if depth and ch in "{}":
            depth[-1] += 1 if ch == "{" else -1
            if depth[-1] == 0:
                depth.pop()
                j = i + 1  # back inside the template literal
                while j < n and text[j] != "`":
                    if text[j] == "\\":
                        j += 2
                        continue
                    if text.startswith("${", j):
                        break
                    j += 1
                if j < n and text.startswith("${", j):
                    depth.append(1)
                    i = j + 2
                else:
                    i = j + 1
                continue
            i += 1
            continue
        if text.startswith(name, i) and (i == 0 or not word.match(text[i - 1])) and \
                (i + len(name) >= n or not word.match(text[i + len(name)])):
            out.append(i)
            i += len(name)
            continue
        if word.match(ch):
            while i < n and word.match(text[i]):
                i += 1
            continue
        i += 1
    return out


def _apply(text: str, hits: list[int], old: str, new: str) -> str:
    parts, last = [], 0
    for h in sorted(hits):
        parts.append(text[last:h])
        parts.append(new)
        last = h + len(old)
    parts.append(text[last:])
    return "".join(parts)


def _defines(lang: str, text: str, name: str, hits: list[int]) -> list[int]:
    """Lines where `name` is defined (only real code positions count, not comments or strings)."""
    code = set(hits)
    pats = [DEFN] + ([PY_ASSIGN] if lang in ("python", "cython") else [])
    lines = set()
    for pat in pats:
        for m in re.finditer(pat.format(name=re.escape(name)), text, re.M):
            start = next(m.start(g) for g in ("n", "g", "j") if g in m.groupdict() and m.group(g))
            if start in code:
                lines.add(_line(text, start))
    return sorted(lines)


def _raw(root: Path, rel: str) -> tuple[Path, bytes, os.stat_result]:
    path = studio._path(root, rel)
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_BINARY", 0)
    try:
        with os.fdopen(os.open(path, flags), "rb") as f:
            info = os.fstat(f.fileno())
            on_path = path.lstat()
            if not stat.S_ISREG(info.st_mode) or (info.st_dev, info.st_ino) != (on_path.st_dev, on_path.st_ino):
                raise HTTPException(409, f"{rel} changed while reading it.")
            data = f.read(MAX_FILE_BYTES + 1)
    except OSError:
        raise HTTPException(403, f"{rel} can't be read.") from None
    if len(data) > MAX_FILE_BYTES:
        raise HTTPException(413, f"{rel} is too big to change safely.")
    return path, data, info


BOM = b"\xef\xbb\xbf"


def _text(data: bytes) -> tuple[str, bool]:
    return data[len(BOM):].decode("utf-8") if data.startswith(BOM) else data.decode("utf-8"), data.startswith(BOM)


def _atomic(path: Path, data: bytes, mode: int) -> None:
    tmp: Optional[Path] = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".automoto-rename-", delete=False) as out:
            tmp = Path(out.name)
            out.write(data)
            out.flush()
            os.fsync(out.fileno())
        os.chmod(tmp, mode)
        os.replace(tmp, path)
        tmp = None
    finally:
        if tmp is not None:
            tmp.unlink(missing_ok=True)


