def _match(call: dict, routes: list[dict]) -> tuple[list[dict], str]:
    def ok_method(r):
        return r["method"] in ("ANY", call["method"]) or (call["method"] == "GET" and r["method"] == "HEAD")
    segs = call["path"].split("/")
    exact = [r for r in routes if r["path"] == call["path"] and ok_method(r)]
    if exact:
        return exact, "exact"
    param = [r for r in routes if ok_method(r) and len(r["path"].split("/")) == len(segs) and all(
        a == b or a == "{}" or b == "{}" for a, b in zip(r["path"].split("/"), segs))]
    if param:
        return param, "pattern"
    if any(r["path"] == call["path"] for r in routes):
        return [], "a route has this address but a different method"
    return [], "no route in this project has this address"


def _handler_models(root: Path, scan: dict, route: dict, names: set[str]) -> list[str]:
    """Data models named in the handler body: up to 80 lines, stopping at the next route (only if unchanged)."""
    f = scan["files"].get(route["file"])
    got = _read(root, route["file"]) if f else None
    if not got or got[1] != f["sha256"]:
        return []
    later = [r["line"] for r in f["routes"] if r["line"] > route["line"]]
    stop = min([route["line"] + 80] + later) - 1
    body = "\n".join(got[0].split("\n")[route["line"]: stop])  # after the route line, up to the next route
    return sorted(n for n in names if re.search(rf"\b{re.escape(n)}\b", body))[:12]


def trace(root: Path) -> dict:
    scan = _scan(root)
    files = scan["files"]
    routes = [r for f in files.values() for r in f["routes"]]
    calls = [c for f in files.values() for c in f["calls"]]
    names = {m["name"] for f in files.values() for m in f["models"]}
    chains, possible, unknown, used = [], [], [], set()
    for c in calls:
        hits, how = _match(c, routes)
        if hits and not c["variable_base"]:
            for r in hits[:3]:
                used.add((r["file"], r["line"], r["method"], r["path"]))
            r = hits[0]
            chains.append({"call": c, "route": r, "match": how, "also": len(hits) - 1,
                           "models": _handler_models(root, scan, r, names)})
            continue
        if c["variable_base"]:
            near = [r for r in routes if c["path"] != "/" and r["path"] != "/" and (
                r["path"].endswith(c["path"]) or c["path"].endswith(r["path"]))]
            if hits or near:
                possible.append({"call": c, "routes": (hits or near)[:3],
                                 "why": "the address starts with a variable, so the full address isn't known"})
            else:
                unknown.append({"call": c, "why": "the address starts with a variable and no route looks like it"})
            continue
        unknown.append({"call": c, "why": how})
    total = len([c for c in calls if not c["variable_base"]])
    lonely = [r for r in routes if (r["file"], r["line"], r["method"], r["path"]) not in used]
    matched_calls = len({(c["call"]["file"], c["call"]["line"], c["call"]["path"]) for c in chains})
    state = "none" if not total else ("passed" if matched_calls == total else "failed")
    return {"schema": SCHEMA, "state": state, "routes": len(routes), "calls": len(calls),
            "matched": matched_calls, "countable": total,
            "summary": (f"{matched_calls} of {total} calls matched a route" if total else
                        "Calls use a changing address, so none could be matched for sure" if calls else
                        "No frontend calls to this project's API were found"),
            "chains": chains[:MAX_LIST], "possible": possible[:MAX_LIST], "unknown": unknown[:MAX_LIST],
            "routes_without_calls": lonely[:MAX_LIST],
            "note": "Only addresses written out in the code are matched. Nothing is guessed.",
            "budget": scan["budget"], **SAFETY}


