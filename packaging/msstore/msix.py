"""Microsoft Store (MSIX) package: version mapping and AppxManifest.xml, generated from automoto/brand.py.

    python packaging/msstore/msix.py version 5.6.0-beta.3          # -> 5.6.3.0
    python packaging/msstore/msix.py manifest --version 5.6.0-beta.3 --out stage/AppxManifest.xml

The Store identity comes from Partner Center (Product identity page). Put the values in the repository variables
MSSTORE_IDENTITY_NAME, MSSTORE_PUBLISHER, MSSTORE_PUBLISHER_DISPLAY_NAME and MSSTORE_DISPLAY_NAME (the reserved app
name); until then the placeholders below are used, which build and validate but can't be uploaded.

Version rule (Microsoft): four numbers, each 0-65535, the first not 0, and the LAST MUST BE 0 for Store packages
(it's reserved for the Store). So the app version X.Y.Z[-beta.N] maps to X.Y.(Z*100 + N).0, and a stable release to
X.Y.(Z*100 + 99).0, which is always higher than its betas:
    5.6.0-beta.3 -> 5.6.3.0     5.6.0 -> 5.6.99.0     5.6.1-beta.1 -> 5.6.101.0     5.6.1 -> 5.6.199.0
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from automoto import brand  # noqa: E402

PLACEHOLDER = {"MSSTORE_IDENTITY_NAME": "ymmiah.AutoMotoAIBeta-placeholder",
               "MSSTORE_PUBLISHER": "CN=00000000-0000-0000-0000-000000000000",
               "MSSTORE_PUBLISHER_DISPLAY_NAME": brand.PUBLISHER,
               "MSSTORE_DISPLAY_NAME": f"{brand.DEFAULT_NAME} (Beta)"}
APP_ID = "AutoMotoAI"
EXECUTABLE = f"{brand.DEFAULT_NAME}.exe"  # Tauri's mainBinaryName
DESCRIPTION = f"{brand.TAGLINE}. Beta."
MIN_WINDOWS = "10.0.17763.0"  # Windows 10 1809 (WebView2 and MSIX full-trust apps)
MAX_TESTED = "10.0.26100.0"   # Windows 11 24H2


def msix_version(version: str) -> str:
    m = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)(?:-beta\.(\d+))?", version.strip())
    if not m:
        raise ValueError(f"can't map version {version!r} (expected X.Y.Z or X.Y.Z-beta.N)")
    x, y, z = int(m[1]), int(m[2]), int(m[3])
    n = int(m[4]) if m[4] is not None else 99
    if m[4] is not None and not 1 <= n <= 98:
        raise ValueError("beta number must be 1-98 (99 is the stable release)")
    build = z * 100 + n
    if x == 0 or max(x, y, build) > 65535:
        raise ValueError(f"version {version} doesn't fit the MSIX rules")
    return f"{x}.{y}.{build}.0"


def identity(env: dict[str, str] | None = None) -> dict[str, str]:
    env = os.environ if env is None else env
    vals = {k: (env.get(k) or "").strip() or v for k, v in PLACEHOLDER.items()}
    if not re.fullmatch(r"[A-Za-z0-9.\-]{3,50}", vals["MSSTORE_IDENTITY_NAME"]):
        raise ValueError("MSSTORE_IDENTITY_NAME: 3-50 letters, digits, dots or dashes (copy it from Partner Center)")
    if not vals["MSSTORE_PUBLISHER"].startswith("CN="):
        raise ValueError("MSSTORE_PUBLISHER must look like CN=... (copy it from Partner Center)")
    return vals


def is_placeholder(env: dict[str, str] | None = None) -> bool:
    env = os.environ if env is None else env
    return not (env.get("MSSTORE_IDENTITY_NAME") and env.get("MSSTORE_PUBLISHER"))


def manifest(version: str, env: dict[str, str] | None = None) -> str:
    ids = identity(env)
    a = lambda s: quoteattr(s)  # noqa: E731
    name = ids["MSSTORE_DISPLAY_NAME"]
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by packaging/msstore/msix.py from automoto/brand.py (app version {escape(version)}). Don't edit. -->
<Package xmlns="http://schemas.microsoft.com/appx/manifest/foundation/windows10"
         xmlns:uap="http://schemas.microsoft.com/appx/manifest/uap/windows10"
         xmlns:rescap="http://schemas.microsoft.com/appx/manifest/foundation/windows10/restrictedcapabilities"
         IgnorableNamespaces="uap rescap">
  <Identity Name={a(ids["MSSTORE_IDENTITY_NAME"])} Publisher={a(ids["MSSTORE_PUBLISHER"])}
            Version="{msix_version(version)}" ProcessorArchitecture="x64" />
  <Properties>
    <DisplayName>{escape(name)}</DisplayName>
    <PublisherDisplayName>{escape(ids["MSSTORE_PUBLISHER_DISPLAY_NAME"])}</PublisherDisplayName>
    <Logo>Assets\\StoreLogo.png</Logo>
    <Description>{escape(DESCRIPTION)}</Description>
  </Properties>
  <Dependencies>
    <TargetDeviceFamily Name="Windows.Desktop" MinVersion="{MIN_WINDOWS}" MaxVersionTested="{MAX_TESTED}" />
  </Dependencies>
  <Resources>
    <Resource Language="en-us" />
  </Resources>
  <Applications>
    <Application Id="{APP_ID}" Executable={a(EXECUTABLE)} EntryPoint="Windows.FullTrustApplication">
      <uap:VisualElements DisplayName={a(name)} Description={a(DESCRIPTION)}
                          BackgroundColor="transparent"
                          Square150x150Logo="Assets\\Square150x150Logo.png" Square44x44Logo="Assets\\Square44x44Logo.png">
        <uap:DefaultTile Wide310x150Logo="Assets\\Wide310x150Logo.png" Square71x71Logo="Assets\\Square71x71Logo.png"
                         Square310x310Logo="Assets\\Square310x310Logo.png" ShortName={a(brand.DEFAULT_NAME)}>
          <uap:ShowNameOnTiles>
            <uap:ShowOn Tile="square150x150Logo" />
          </uap:ShowNameOnTiles>
        </uap:DefaultTile>
        <uap:SplashScreen Image="Assets\\SplashScreen.png" BackgroundColor="{brand.COLORS['bg']}" />
      </uap:VisualElements>
    </Application>
  </Applications>
  <Capabilities>
    <Capability Name="internetClient" />
    <rescap:Capability Name="runFullTrust" />
  </Capabilities>
</Package>
"""


def main(argv: list[str]) -> int:
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["version", "manifest"])
    ap.add_argument("app_version", nargs="?")
    ap.add_argument("--version", dest="version_opt")
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    v = a.version_opt or a.app_version
    if not v:
        ap.error("give the app version, e.g. 5.6.0-beta.3")
    if a.cmd == "version":
        print(msix_version(v))
        return 0
    text = manifest(v)
    if a.out:
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text(text, encoding="utf-8")
        if is_placeholder():
            print("::warning::MSSTORE_IDENTITY_NAME / MSSTORE_PUBLISHER not set - placeholder identity "
                  "(fine for testing, Partner Center will reject the upload)")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
