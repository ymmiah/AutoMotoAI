def test_untrusted_run_and_changed_files_cannot_reuse_approval(project):
    client, root = project
    assert run(client, root).status_code == 403
    trust(client, root)
    summary = inspect(client, root).json()
    tool = next(x for x in summary["toolchains"] if x["name"] == "cargo")
    if tool["status"] != "installed_not_executed":
        pytest.skip("Installed Cargo unavailable")
    payload = {"project": str(root), "task": "cargo_version", "tool": "cargo",
               "expected_manifest_sha256": summary["manifest_sha256"],
               "expected_source_sha256": summary["source_sha256"],
               "expected_executable": tool["executable"],
               "expected_sha256": tool["sha256"],
               "confirmed": True, "accept_unsandboxed_execution_and_write_risk": True}
    assert client.post(BASE + "/run", headers=AUTH, json={
        **payload, "confirmed": False}).status_code == 422
    assert client.post(BASE + "/run", headers=AUTH, json={
        **payload, "expected_sha256": "0" * 64}).status_code == 409
    assert client.post(BASE + "/run", headers=AUTH, json={
        **payload, "task": "rustc_version"}).status_code == 422
    (root / "crates/core/src/lib.rs").write_text(LIB + "\n// changed\n")
    assert client.post(BASE + "/run", headers=AUTH, json=payload).status_code == 409
    payload["expected_source_sha256"] = inspect(client, root).json()["source_sha256"]
    (root / "Cargo.lock").write_text(LOCK + "\n#changed\n")
    assert client.post(BASE + "/run", headers=AUTH, json=payload).status_code == 409


def test_real_rustc_and_cargo_version_and_build_test_check_clippy_fmt(project):
    client, root = project
    trust(client, root)
    before = snapshot(root)
    for task, tool in (("cargo_version", "cargo"), ("rustc_version", "rustc"),
                       ("check", "cargo"), ("build", "cargo"), ("test", "cargo"),
                       ("clippy", "cargo"), ("fmt_check", "cargo")):
        response = run(client, root, task=task, tool=tool)
        assert response.status_code == 200, (task, response.text)
        data = response.json()
        if data["status"] != "completed":
            pytest.fail("Rust "+task+" failed:\n"+data["output"], pytrace=False)
        assert data["temporary_build_artifacts_deleted"] is True
        assert data["external_process_unsandboxed"] is True
        assert data["agent_deployment_approved"] is False
        assert data["deployment_started"] is False
        assert data["package_installation_performed_by_app"] is False
    assert snapshot(root) == before, "V19 tools must not leave build outputs in source"


