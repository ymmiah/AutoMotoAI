def inspect(client, root):
    return client.get(BASE + "/inspect", headers=AUTH, params={"project": str(root)})


def trust(client, root):
    response = client.post("/api/developer/studio/trust", headers=AUTH,
                           json={"project": str(root), "trusted": True, "confirmed": True})
    assert response.status_code == 200, response.text


def run(client, root, task="cargo_version", tool="cargo", **kwargs):
    response = inspect(client, root)
    assert response.status_code == 200, response.text
    info = response.json()
    binary = next(x for x in info["toolchains"] if x["name"] == tool)
    if binary["status"] != "installed_not_executed":
        pytest.skip("Pinned installed Rust tool " + tool + " unavailable.")
    body = {"project": str(root), "task": task, "tool": tool,
            "expected_manifest_sha256": info["manifest_sha256"],
            "expected_source_sha256": info["source_sha256"],
            "expected_executable": binary["executable"],
            "expected_sha256": binary["sha256"],
            "confirmed": True, "accept_unsandboxed_execution_and_write_risk": True}
    body.update(kwargs)
    return client.post(BASE + "/run", headers=AUTH, json=body)


def snapshot(root):
    return {p.relative_to(root).as_posix(): p.read_bytes()
            for p in root.rglob("*") if p.is_file()}


def test_rust_two_crate_inspection_is_nonexecuting_and_has_provenance(project):
    client, root = project
    before = snapshot(root)
    reply = inspect(client, root)
    assert reply.status_code == 200, reply.text
    body = reply.json()
    assert body["workspace"] is True and body["safe_to_offer_runs"] is True
    assert {x["name"] for x in body["crates"]} == {
        "automoto-v19-core", "automoto-v19-cli"}
    assert "Cargo.lock" in body["manifests"]
    assert {x["path"] for x in body["files"]} == {
        "crates/core/src/lib.rs", "crates/cli/src/main.rs"}
    assert any(x["name"] == "greet" for x in body["symbols"])
    assert body["rust_analyzer_lsp"].startswith("Existing V6")
    assert body["debugger"].startswith("Existing V8")
    assert len(body["debug_adapters"]) == 2
    assert body["tool_executed"] is False
    assert body["download_requested"] is False
    assert body["deployment_started"] is False
    assert body["central_agent_studio"] == "developer"
    assert body["agent_deployment_handoff_required"] is True
    assert snapshot(root) == before


def test_reject_workspace_traversal_globs_duplicate_members_and_invalid_toml(project):
    client, root = project
    config = root / "Cargo.toml"
    for members in ('["../outside"]', '["crates/*"]',
                    '["crates/core", "crates/core"]', '["/tmp/external"]'):
        config.write_text('[workspace]\nmembers = '+members+'\n')
        response = inspect(client, root)
        assert response.status_code in (403, 422), (members, response.text)
    config.write_text("[workspace\nmembers = []\n")
    assert inspect(client, root).status_code == 422


def test_symlinked_workspace_member_is_forbidden(project, tmp_path):
    client, root = project
    outside = tmp_path / "outside"
    outside.mkdir()
    (outside / "Cargo.toml").write_text(CORE_CARGO)
    (root / "Cargo.toml").write_text(
        '[workspace]\nmembers = ["linked"]\n')
    try:
        (root / "linked").symlink_to(outside, target_is_directory=True)
    except (OSError, NotImplementedError):
        pytest.skip("No symlinks supported on runner.")
    response = inspect(client, root)
    assert response.status_code in (403, 422)


