def test_v37_map_resolves_imports_across_languages(env):
    client, project = env
    r = post(client, "/map", project=str(project))
    assert r.status_code == 200, r.text
    data = r.json()
    langs = {x["name"] for x in data["languages"]}
    assert {"TypeScript", "Python", "Go", "Rust", "SQL", "Prisma"} <= langs
    assert data["source_executed"] is False and data["source_modified"] is False and data["index_persisted"] is False
    links = post(client, "/file", project=str(project), path="web/src/api.ts").json()
    assert any(e["to"] == "web/src/util/fmt.ts" for e in links["uses"])  # tsconfig alias
