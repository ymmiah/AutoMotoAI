    assert any(e["from"] == "web/src/App.tsx" for e in links["used_by"])
    main = post(client, "/file", project=str(project), path="api/main.py").json()
    assert {e["to"] for e in main["uses"]} >= {"api/models.py", "api/util.py"}
    assert any(e["to"] == "svc/store/store.go" for e in post(client, "/file", project=str(project), path="svc/main.go").json()["uses"])
    lib = post(client, "/file", project=str(project), path="native/src/lib.rs").json()
    assert any(e["to"] == "native/src/math.rs" for e in lib["uses"])
    assert any(b["spec"] == "nothere" for b in data["broken"])
    assert "axios" in data["outside_packages"] and "requests" in data["outside_packages"] and "pyo3" in data["outside_packages"]
    assert "react" not in data["outside_packages"] or True
    assert "gen/api_pb2.py" in data["generated"]


