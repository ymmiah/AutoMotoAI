def post(client, endpoint, **body):
    return client.post(P + endpoint, headers=AUTH, json=body)


def trust(client, project):
    r = client.post(BASE + "/trust", headers=AUTH, json={"project": str(project), "trusted": True, "confirmed": True})
    assert r.status_code == 200, r.text


def edge(data_edges, a, b):
    return any(e["from"] == a and e["to"] == b for e in data_edges)


