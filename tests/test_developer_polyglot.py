def test_v40_monorepo_packages_bindings_and_commands(env):
    client, project = env
    extra = {
        "package.json": '{"name": "root", "private": true, "workspaces": ["web", "shared"]}',
        "shared/package.json": '{"name": "shared", "version": "1.0.0"}',
        "shared/index.js": "module.exports = {};\n",
        "Cargo.toml": '[workspace]\nmembers = ["native", "core"]\n',
        "core/Cargo.toml": '[package]\nname = "core"\n\n[dependencies]\nnative = { path = "../native" }\n',
        "core/src/lib.rs": "pub fn x() {}\n",
        "ext/binding.gyp": '{"targets": [{"target_name": "addon", "sources": ["addon.c"]}]}',
        "ext/addon.c": "#include <node_api.h>\nNAPI_MODULE(addon, Init)\n",
        "pyext/spam.c": "#include <Python.h>\nPyMODINIT_FUNC PyInit_spam(void) { return 0; }\n",
        "svc/cgo.go": 'package main\n\n// #include <stdio.h>\nimport "C"\n',
    }
    for rel, text in extra.items():
        (project / rel).parent.mkdir(parents=True, exist_ok=True)
        (project / rel).write_text(text, encoding="utf-8")
    data = post(client, "/packages", project=str(project)).json()
    assert data["monorepo"] is True and data["source_executed"] is False
    tools = {t["tool"]: t["members"] for t in data["tools"]}
    assert tools["npm workspaces"] == ["web", "shared"] and tools["Cargo workspace"] == ["native", "core"]
    pk = {p["path"]: p for p in data["packages"]}
    assert "shared" in pk["web"]["depends_on"] and "native" in pk["core"]["depends_on"]
    assert any(c["command"] == "cd web && npm run build" for c in pk["web"]["commands"])
    assert any(c["command"] == "cd native && cargo build" for c in pk["native"]["commands"])
    assert pk["web"]["languages"][0]["name"] == "TypeScript"
    labels = {b["label"] for b in data["bindings"]}
    assert {"Rust ↔ Python (PyO3)", "C/C++ ↔ JavaScript (node-gyp)", "C/C++ ↔ JavaScript (Node-API)",
            "C ↔ Python (CPython C API)", "Go ↔ C (cgo)"} <= labels
    assert any(g["file"] == "gen/api_pb2.py" for g in data["generated"])


