def test_v39_rename_blocks_ambiguity_then_previews_with_impact(env):
    client, project = env
    trust(client, project)
    amb = post(client, "/rename/preview", project=str(project), old="loadUsers", new="fetchUsers").json()
    assert amb["state"] == "blocked" and len(amb["choices"]) == 2 and amb["action_sha256"] is None
    ok = post(client, "/rename/preview", project=str(project), old="loadUsers", new="fetchUsers", path="web/src/api.ts").json()
    assert ok["state"] == "ready", ok
    by = {f["path"]: f for f in ok["files"]}
    assert set(by) == {"web/src/api.ts", "web/src/App.tsx"}
    assert by["web/src/App.tsx"]["count"] == 2  # import + call; the comment and the string are left alone
    assert any(w["kind"] == "outside" and "web/src/Other.tsx" in w["files"] for w in ok["warnings"])
    assert (project / "web/src/App.tsx").read_text(encoding="utf-8") == FIXTURE["web/src/App.tsx"]
    applied = post(client, "/rename/apply", project=str(project), action_sha256=ok["action_sha256"], confirmed=True)
    assert applied.status_code == 200, applied.text
    app = (project / "web/src/App.tsx").read_text(encoding="utf-8")
    assert "import { fetchUsers } from './api';" in app and "// loadUsers in a comment" in app and "'loadUsers'" in app
    assert (project / "web/src/Other.tsx").read_text(encoding="utf-8") == FIXTURE["web/src/Other.tsx"]
    again = post(client, "/rename/apply", project=str(project), action_sha256=ok["action_sha256"], confirmed=True)
    assert again.status_code == 409  # single use
    undo = post(client, "/rename/undo", project=str(project), undo_id=applied.json()["undo_id"])
    assert undo.status_code == 200, undo.text
    assert (project / "web/src/App.tsx").read_text(encoding="utf-8") == FIXTURE["web/src/App.tsx"]


