def test_v38_trace_matches_only_written_addresses(env):
    client, project = env
    data = post(client, "/trace", project=str(project)).json()
    chains = {(c["call"]["method"], c["call"]["path"], c["route"]["handler"]) for c in data["chains"]}
    assert ("GET", "/api/users", "list_users") in chains
    assert ("GET", "/api/users/{}", "get_user") in chains
    assert ("POST", "/api/orders", "create_order") in chains
    users = next(c for c in data["chains"] if c["route"]["handler"] == "list_users")
    assert users["models"] == ["User"]
    assert [u["call"]["path"] for u in data["unknown"]] == ["/api/nowhere"]
    assert [p["call"]["raw"] for p in data["possible"]] == ["${BASE}/api/users"]
    assert not any("example.com" in c["call"]["raw"] for c in data["chains"] + data["unknown"] + data["possible"])
    assert data["matched"] == 3 and data["countable"] == 4 and data["state"] == "failed"
    assert data["summary"] == "3 of 4 calls matched a route"
    assert any(r["handler"] == "purge" for r in data["routes_without_calls"])


