// Document Assistant v2: deterministic editor history, outline, tables, safe preview.
const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const path=require('node:path');
(async()=>{
  const file=path.resolve(__dirname,"../../../automoto/web/static/document-editor-model.js");
  const code=readFileSync(file,"utf8");
  const model=await import("data:text/javascript;base64,"+Buffer.from(code).toString("base64"));
  const initial={name:"Report",markdown:"# Report\n\nOriginal text.",options:{...model.DEFAULT_LAYOUT}};
  const history=model.createDocumentHistory(initial);
  assert.deepEqual(history.state().value,initial);
  assert.equal(history.state().canUndo,false);
  const afterTyping={...initial,markdown:initial.markdown+"A"};
  const afterMoreTyping={...initial,markdown:initial.markdown+"AB"};
  history.commit(afterTyping,{kind:"source",time:1000,coalesce:true});
  history.commit(afterMoreTyping,{kind:"source",time:1200,coalesce:true});
  assert.equal(history.state().undoDepth,1,"rapid typing coalesces into one undo");
  assert.deepEqual(history.undo(),initial);
  assert.deepEqual(history.redo(),afterMoreTyping);
  const changedSettings={...afterMoreTyping,options:{...initial.options,
    orientation:"landscape",margins_cm:3}};
  history.commit(changedSettings,{kind:"layout",time:3000});
  assert.equal(history.undo().options.orientation,"portrait");
  assert.equal(history.redo().options.orientation,"landscape");
  history.reset(initial);
  assert.equal(history.state().canUndo,false,"opening a new draft resets history");
  assert.equal(history.redo(),null);
  const limited=model.createDocumentHistory(initial,3);
  for(let i=0;i<9;i++)limited.commit({...initial,markdown:"value"+i});
  assert.equal(limited.state().undoDepth,3,"bounded memory history");
  const oldDefaults=model.layoutOptions();
  assert.equal(oldDefaults.page_size,"A4");
  assert.equal(model.layoutOptions({orientation:"landscape",evil:"ignored"}).evil,undefined);
  const headings=model.documentOutline("# First\n## Second\nPlain\n### Third\n");
  assert.deepEqual(headings.map(h=>h.level),[1,2,3]);
  assert.equal(headings[1].text,"Second");
  assert.equal(headings[1].offset,8);
  const replacement=model.formatHeading("Line one\nPlain heading\nOther",14,14,3);
  assert.equal(replacement.value,"Line one\n### Plain heading\nOther");
  const inserted=model.createTable("# Report\n\n",9,9);
  assert.match(inserted.value,/\| Column A \| Column B \| Column C \|/);
  const cursor=inserted.value.indexOf("Value 1");
  const appended=model.appendTableRow(inserted.value,cursor);
  assert.ok(appended);
  assert.equal((appended.value.match(/\| New value/g)||[]).length,3,
    'the added table row contains one new editable cell for each column');
  assert.equal(model.appendTableRow("No table here.",4),null);
  const escape=s=>String(s).replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
  const output=model.renderDocumentPreview("# Head\n\n| A | B |\n| --- | --- |\n| 1 | 2 |\n\n<script>alert(1)</script>",escape);
  assert.match(output,/<h1>Head<\/h1>/);
  assert.match(output,/<table class="da-table">/);
  assert.match(output,/<th>A<\/th>/);
  assert.match(output,/<td>2<\/td>/);
  assert.ok(!output.includes("<script>"),"preview cannot embed untrusted HTML");
  assert.match(output,/&lt;script&gt;/);
  console.log("Document Assistant v2 editor history, outline, table and safe preview checks passed.");
})().catch(e=>{console.error(e);process.exitCode=1;});
